/**
 * Suppliers contract (domain 03): public registration and membership requests (SUP-02), the supplier organization
 * profile and legal-identity changes (SUP-03), the evidence library and per-buyer sharing (SUP-05), the buyer
 * supplier directory (BUY-31) and relationship record (BUY-32), and the operator duplicate, registration and
 * identity-change reviews (OPS-01).
 *
 * PRD §5.2 FR-02, BR-03, BR-44, BR-45; AC-07 (registration is not qualification); ADR-0012; DD-17, DD-27, DD-28.
 * Schemas live in `./suppliers/schemas.ts` and are re-exported here, so the SPA imports only `@contracts/suppliers`.
 *
 * Audience rules the Stage B service must honor exactly as the mock API does:
 * - `/public/*` registration endpoints are rate-limited (DD-28) and never disclose another organization.
 * - `/supplier/*` returns only the caller's own organization; `buyer_supplier_relationships` and
 *   `relationship_contacts` are [R] and never reach a supplier response (DD-03).
 * - `/buyer/*` returns only this buyer's relationship, contacts and qualification decisions, plus evidence the
 *   supplier shared with this buyer (BR-45). Other buyers' provisional records are not found.
 * - Financial evidence: `supplier.financial.view` (supplier) and `qualification.financial_review` (buyer).
 */
