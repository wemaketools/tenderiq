/**
 * Tender package documents of the publication fixtures.
 *
 * Each document version is a real (tiny) PDF generated deterministically from its static description, so the
 * `sizeBytes` and `sha256` the contracts publish are the exact size and digest of the bytes a download returns.
 * Nothing is random and nothing changes at runtime.
 */
import { createHash } from 'node:crypto';

import type { DocumentsClassification } from '../../../contracts/enums.js';
import type { PackageDocument } from '../../../contracts/publication.js';

/**
 * Who may download a package document:
 * - `public`: anyone, subject to the buyer's `public_document_policy`;
 * - `participants`: organizations taking part (interest registered, invitation accepted or access granted);
 * - `confidential`: participants with access granted (where access is requested) AND the confidentiality
 *   undertaking accepted.
 */
export type DocumentAccessRule = 'public' | 'participants' | 'confidential';

/** A package document as stored by the fixtures (the tender id is on the owning tender). */
export interface FixtureDocument extends PackageDocument {
  readonly accessRule: DocumentAccessRule;
  /** The static description the bytes are generated from (internal; never returned). */
  readonly spec: DocumentSpec;
}

/** Keeps a PDF text operand printable ASCII and escapes the PDF string delimiters. */
function pdfText(value: string): string {
  return value
    .replace(/[–—]/g, '-')
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[^\x20-\x7e]/g, '?')
    .replace(/([()\\])/g, '\\$1');
}

/** Builds a one-page PDF with a title and a few lines of text. */
export function prototypePdf(title: string, lines: readonly string[]): Buffer {
  const textOps = [
    'BT',
    '/F1 16 Tf',
    '56 780 Td',
    `(${pdfText(title)}) Tj`,
    '/F1 11 Tf',
    ...lines.flatMap((line) => ['0 -22 Td', `(${pdfText(line)}) Tj`]),
    'ET',
  ].join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    `<< /Length ${Buffer.byteLength(textOps, 'latin1')} >>\nstream\n${textOps}\nendstream`,
  ];
  let body = '%PDF-1.4\n';
  const offsets: number[] = [];
  objects.forEach((object, index) => {
    offsets.push(Buffer.byteLength(body, 'latin1'));
    body += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xrefOffset = Buffer.byteLength(body, 'latin1');
  body += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) {
    body += `${String(offset).padStart(10, '0')} 00000 n \n`;
  }
  body += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;
  return Buffer.from(body, 'latin1');
}

/** The static description of one document version. */
export interface DocumentSpec {
  readonly documentId: number;
  readonly title: string;
  readonly fileName: string;
  readonly classification: DocumentsClassification;
  readonly accessRule: DocumentAccessRule;
  readonly versionNo: number;
  readonly precedence: number | null;
  readonly publishedAt: string;
  readonly addendumNo: number | null;
  /** The tender reference and buyer printed on the page. */
  readonly tenderReference: string;
  readonly buyerName: string;
}

/** The PDF bytes of a document version. */
export function documentBytes(spec: DocumentSpec): Buffer {
  return prototypePdf(spec.title, [
    `${spec.buyerName} - ${spec.tenderReference}`,
    `File: ${spec.fileName} (version ${spec.versionNo})`,
    `Issued: ${spec.publishedAt}`,
    spec.addendumNo === null ? 'Original issue' : `Issued with addendum ${spec.addendumNo}`,
    'TenderIQ prototype: illustrative content of the demo world.',
  ]);
}

/** Builds a fixture document whose size and digest are those of its generated bytes. */
export function packageDocument(spec: DocumentSpec): FixtureDocument {
  const bytes = documentBytes(spec);
  return {
    documentId: spec.documentId,
    versionId: spec.documentId * 10 + spec.versionNo,
    title: spec.title,
    classification: spec.classification,
    language: 'en',
    fileName: spec.fileName,
    contentType: 'application/pdf',
    sizeBytes: bytes.length,
    sha256: createHash('sha256').update(bytes).digest('hex'),
    versionNo: spec.versionNo,
    precedence: spec.precedence,
    publishedAt: spec.publishedAt,
    addendumNo: spec.addendumNo,
    accessRule: spec.accessRule,
    spec,
  };
}
