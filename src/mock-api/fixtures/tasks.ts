export interface FixtureTaskEvent {
  readonly at: Instant;
  readonly actorUserId: number | null;
  readonly status: TasksStatus;
  readonly note: string | null;
}

export interface FixtureTask {
  readonly id: number;
  readonly tenantId: number;
  readonly assigneeUserId: number | null;
  readonly groupId: number | null;
  readonly title: string;
  readonly description: string | null;
  readonly taskType: TasksTaskType;
  readonly sourceType: string;
  readonly sourceId: number | null;
  readonly sourceReference: string | null;
  readonly sourceLinkPath: string | null;
  readonly sourceOwnerUserId: number | null;
  readonly dueAt: Instant | null;
  readonly priority: TasksPriority;
  readonly status: TasksStatus;
  readonly escalationUserId: number | null;
  readonly delegatedFromUserId: number | null;
  readonly createdAt: Instant;
  readonly completedAt: Instant | null;
  readonly completedByUserId: number | null;
  readonly outcomeNote: string | null;
  readonly history: readonly FixtureTaskEvent[];
  /** Completed by its source command (an approval decision, a score submission), never by "complete". */
  readonly completedBySource: boolean;
  /** Who may take the task over: members holding one of these permissions (empty = not reassignable). */
  readonly reassignPermissions: readonly PermissionCode[];
  /** Colleagues with a known conflict on the source record (never offered, REASSIGNEE_CONFLICTED). */
  readonly conflictedUserIds: readonly number[];
}

interface TaskSpec {
  readonly id: number;
  readonly tenant: TenantSlug;
  readonly assignee: string | null;
  readonly groupId?: number;
  readonly title: string;
  readonly description?: string;
  readonly type: TasksTaskType;
  readonly source: { type: string; id: number | null; reference: string | null; link: string | null };
  readonly sourceOwner?: string;
  readonly dueAt: Instant | null;
  readonly priority?: TasksPriority;
  readonly status?: TasksStatus;
  readonly escalation?: string;
  readonly delegatedFrom?: string;
  readonly createdAt: Instant;
  readonly createdBy?: string;
  readonly completed?: { at: Instant; by: string; note: string | null };
  readonly events?: readonly { at: Instant; by: string | null; status: TasksStatus; note: string | null }[];
  readonly bySource?: boolean;
  readonly reassign?: readonly PermissionCode[];
  readonly conflicted?: readonly string[];
}

function task(spec: TaskSpec): FixtureTask {
  const status = spec.status ?? 'open';
  const created: FixtureTaskEvent = {
    at: spec.createdAt,
    actorUserId: spec.createdBy === undefined ? null : uid(spec.createdBy),
    status: 'open',
    note: spec.createdBy === undefined ? 'Created by the workflow.' : null,
  };
  const events = (spec.events ?? []).map((event) => ({
    at: event.at,
    actorUserId: event.by === null ? null : uid(event.by),
    status: event.status,
    note: event.note,
  }));
  const completion: FixtureTaskEvent[] =
    spec.completed === undefined
      ? []
      : [{ at: spec.completed.at, actorUserId: uid(spec.completed.by), status: 'completed', note: spec.completed.note }];
  return {
    id: spec.id,
    tenantId: tid(spec.tenant),
    assigneeUserId: spec.assignee === null ? null : uid(spec.assignee),
    groupId: spec.groupId ?? null,
    title: spec.title,
    description: spec.description ?? null,
    taskType: spec.type,
    sourceType: spec.source.type,
    sourceId: spec.source.id,
    sourceReference: spec.source.reference,
    sourceLinkPath: spec.source.link,
    sourceOwnerUserId: spec.sourceOwner === undefined ? null : uid(spec.sourceOwner),
    dueAt: spec.dueAt,
    priority: spec.priority ?? 'normal',
    status,
    escalationUserId: spec.escalation === undefined ? null : uid(spec.escalation),
    delegatedFromUserId: spec.delegatedFrom === undefined ? null : uid(spec.delegatedFrom),
    createdAt: spec.createdAt,
    completedAt: spec.completed?.at ?? null,
    completedByUserId: spec.completed === undefined ? null : uid(spec.completed.by),
    outcomeNote: spec.completed?.note ?? null,
    history: [created, ...events, ...completion],
    completedBySource: spec.bySource ?? false,
    reassignPermissions: spec.reassign ?? [],
    conflictedUserIds: (spec.conflicted ?? []).map(uid),
  };
}

const approvalSource = (approvalId: number, reference: string) => ({
  type: 'approval_request',
  id: approvalId,
  reference,
  link: `/me/approvals/${approvalId}`,
});

const recordSource = (key: keyof typeof RECORDS, side: 'buyer' | 'supplier' = 'buyer', suffix = '') => {
  const record = RECORDS[key];
  const link = side === 'buyer' ? record.buyerLink : record.supplierLink;
  return { type: record.type, id: record.id, reference: record.reference, link: link === null ? null : `${link}${suffix}` };
};

